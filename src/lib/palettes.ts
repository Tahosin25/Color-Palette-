export const ALL_TAGS = Array.from(
  new Set(PALETTES.flatMap((p) => p.tags)),
).sort();

export function getPaletteById(id: string): Palette | undefined {
  return PALETTES.find((p) => p.id === id);
}

export function getPalettesByTag(tag: string): Palette[] {
  return PALETTES.filter((p) => p.tags.includes(tag));
}

export function getRelatedPalettes(id: string, limit = 4): Palette[] {
  const current = getPaletteById(id);
  if (!current) return PALETTES.slice(0, limit);
  return PALETTES.filter((p) => p.id !== id && p.tags.some((t) => current.tags.includes(t))).slice(0, limit);
}

export function getRandomPalette(): Palette {
  return PALETTES[Math.floor(Math.random() * PALETTES.length)];
}

export function generateRandomPalette(name = "Random Palette"): Palette {
  const randomColor = () => {
    const r = Math.floor(Math.random() * 256);
    const g = Math.floor(Math.random() * 256);
    const b = Math.floor(Math.random() * 256);
    return `#${r.toString(16).padStart(2, "0")}${g.toString(16).padStart(2, "0")}${b.toString(16).padStart(2, "0")}`;
  };
  return {
    id: `rand-${Date.now()}`,
    name,
    colors: [randomColor(), randomColor(), randomColor(), randomColor()],
    tags: ["random", "generated"],
    likes: 0,
    createdAt: new Date().toISOString(),
  };
}
